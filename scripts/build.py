"""Builds dist/ModActivator.asi, and build/ModActivator-tests.asi for the test suites.

The test build is the same plugin plus the exported entry points the tests in
tests/ call. Those entry points are compiled only with MODACTIVATOR_TESTS, so
the release build ships none of them.
"""
from pathlib import Path
import argparse
import concurrent.futures
import os
import shutil
import subprocess
import zipfile

base = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--toolchain', default=os.environ.get('LLVM_MINGW'))
args = parser.parse_args()
if not args.toolchain:
    parser.error('Pass --toolchain PATH or set LLVM_MINGW to your extracted LLVM-MinGW folder')
tc = Path(args.toolchain).resolve() / 'bin'
out = base / 'dist'
out.mkdir(exist_ok=True)
obj = base / 'build'
obj.mkdir(exist_ok=True)

imgui = base / 'vendor/imgui'
minhook = base / 'vendor/minhook/src'
sources = (sorted((base / 'src').rglob('*.cpp'))
           + [imgui / n for n in ['imgui.cpp', 'imgui_draw.cpp', 'imgui_widgets.cpp',
                                  'imgui_tables.cpp', 'backends/imgui_impl_win32.cpp']]
           + sorted(minhook.glob('*.c')) + [minhook / 'hde/hde64.c'])
# Sources holding test entry points; compiled a second time for the test build.
with_tests = {base / 'src/activator.cpp', base / 'src/hooks/input.cpp'}
# The known-mods list is compiled into the plugin: DMM does not install it
# as a file of its own. data/ModActivator.KnownMods.ini is the source.
generated = obj / 'generated'
generated.mkdir(exist_ok=True)
known_mods = (base / 'data/ModActivator.KnownMods.ini').read_text(encoding='utf-8')
delimiter = 'KnownMods'  # raw string delimiters: 16 characters at most
assert ')' + delimiter + '"' not in known_mods
header = ('// Generated by scripts/build.py from data/ModActivator.KnownMods.ini. Do not edit.\n'
          '#pragma once\n'
          'static const char builtInKnownMods[] = R"' + delimiter + '(' + known_mods +
          ')' + delimiter + '";\n')
target = generated / 'known_mods_data.h'
if not target.exists() or target.read_text(encoding='utf-8') != header:
    target.write_text(header, encoding='utf-8')
includes = [base / 'src', generated, imgui, imgui / 'backends', base / 'vendor/minhook/include',
            minhook / 'hde']
# IMGUI_IMPL_WIN32_DISABLE_GAMEPAD: the menu is handed the controller by
# ModActivator itself (see feedController in src/activator.cpp).
flags = ['-O2', '-DNDEBUG', '-DWIN32_LEAN_AND_MEAN', '-DNOMINMAX', '-D_CRT_SECURE_NO_WARNINGS',
         '-DIMGUI_IMPL_WIN32_DISABLE_GAMEPAD', '-fms-extensions']


def compile_one(job):
    src, tests = job
    name = src.relative_to(base).as_posix().replace('/', '_') + ('.tests' if tests else '') + '.o'
    target = obj / name
    compiler = 'x86_64-w64-mingw32-clang.exe' if src.suffix == '.c' else 'x86_64-w64-mingw32-clang++.exe'
    cmd = [str(tc / compiler), '-c', str(src), '-o', str(target)] + flags
    if src.suffix == '.cpp':
        cmd += ['-std=c++17']
    if tests:
        cmd += ['-DMODACTIVATOR_TESTS']
    for inc in includes:
        cmd += ['-I', str(inc)]
    return src, tests, target, subprocess.run(cmd, capture_output=True, text=True)


jobs = [(s, False) for s in sources] + [(s, True) for s in sources if s in with_tests]
results = list(concurrent.futures.ThreadPoolExecutor(max_workers=4).map(compile_one, jobs))
failed = False
for _, _, _, r in results:
    if r.returncode:
        print(r.stdout + r.stderr)
        failed = True
if failed:
    raise SystemExit(1)

libs = ['-ld3d12', '-ldxgi', '-ldwmapi', '-limm32', '-ldxguid', '-luser32', '-lgdi32']


def link(path, tests):
    objects = [str(t) for s, t_flag, t, _ in results
               if t_flag == tests or (not t_flag and s not in with_tests)]
    # With no dllexport in it, the release build would otherwise have every
    # global symbol exported automatically: over a thousand of them.
    subprocess.run([str(tc / 'x86_64-w64-mingw32-clang++.exe'), '-shared', '-static',
                    '-Wl,--exclude-all-symbols', '-o', str(path)] + objects + libs, check=True)
    print('Built ' + str(path))


link(out / 'ModActivator.asi', False)
link(obj / 'ModActivator-tests.asi', True)

# dist/ mirrors bin64: the plugin and its settings file at the top, where
# the ASI loader and DMM put them (DMM does not install a release's
# subfolders), and the documentation and licences in a ModActivator folder
# beside them, for manual installs. ModActivator writes its log into that
# folder too. The known-mods list is inside the plugin (see above).
for name in ['README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md']:
    (out / name).unlink(missing_ok=True)
for name in ['include', 'licenses', 'ModActivator']:
    shutil.rmtree(out / name, ignore_errors=True)
inis = [base / 'ModActivator.ini']
(out / 'ModActivator.KnownMods.ini').unlink(missing_ok=True)
for ini in inis:
    shutil.copy2(ini, out / ini.name)
data = out / 'ModActivator'
data.mkdir()
# The export header is not part of the mod: ModActivator never reads it. Mod
# authors get it in the modder kit below.
# Distributable documentation and required third-party notices.
for name in ['README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'CHANGELOG.md']:
    shutil.copy2(base / name, data / name)
shutil.copytree(base / 'licenses', data / 'licenses')

# The example mod from the modder kit, built so the kit is known to compile;
# tests/test_features.py loads it to check that ModActivator reads its export.
example = base / 'examples/ExampleMod'
subprocess.run([str(tc / 'x86_64-w64-mingw32-clang++.exe'), '-shared', '-static', '-O2',
                '-std=c++17', '-I', str(base / 'include'), '-o', str(obj / 'ExampleMod.asi'),
                str(example / 'ExampleMod.cpp'), '-luser32'], check=True)
print('Built ' + str(obj / 'ExampleMod.asi'))

# The two release archives, named for VERSION.
#   ModActivator-<version>.zip            the mod, laid out from the game folder
#                                         (bin64\...), as users and DMM install it
#   ModActivator-<version>-ModderKit.zip  for mod authors: the export header,
#                                         the guide and the example mod
version = (base / 'VERSION').read_text(encoding='utf-8').strip()
with zipfile.ZipFile(out / f'ModActivator-{version}.zip', 'w', zipfile.ZIP_DEFLATED) as z:
    z.write(out / 'ModActivator.asi', 'bin64/ModActivator.asi')
    for ini in inis:
        z.write(out / ini.name, 'bin64/' + ini.name)
    for path in sorted(p for p in data.rglob('*') if p.is_file()):
        z.write(path, 'bin64/ModActivator/' + path.relative_to(data).as_posix())
with zipfile.ZipFile(out / f'ModActivator-{version}-ModderKit.zip', 'w', zipfile.ZIP_DEFLATED) as z:
    z.write(base / 'docs/MODDERS.md', 'README.md')
    z.write(base / 'include/ModActivatorBindings.h', 'include/ModActivatorBindings.h')
    for name in ['ExampleMod.cpp', 'ExampleMod.ini']:
        z.write(example / name, 'examples/ExampleMod/' + name)
    z.write(base / 'data/ModActivator.KnownMods.ini', 'reference/ModActivator.KnownMods.ini')
    z.write(base / 'LICENSE', 'LICENSE')
print(f'Packed dist/ModActivator-{version}.zip and dist/ModActivator-{version}-ModderKit.zip')
